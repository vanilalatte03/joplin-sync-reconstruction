CREATE TABLE IF NOT EXISTS notes (
 id VARCHAR(100) PRIMARY KEY, title VARCHAR(1000) NOT NULL,
 body CLOB NOT NULL, version BIGINT NOT NULL, deleted BOOLEAN NOT NULL
);
CREATE TABLE IF NOT EXISTS changes (
 seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 note_id VARCHAR(100) NOT NULL, title VARCHAR(1000) NOT NULL,
 body CLOB NOT NULL, version BIGINT NOT NULL, deleted BOOLEAN NOT NULL
);
CREATE TABLE IF NOT EXISTS conflicts (
 op_id VARCHAR(36) PRIMARY KEY, client_id VARCHAR(100) NOT NULL,
 note_id VARCHAR(100) NOT NULL, base_version BIGINT NOT NULL,
 incoming_payload CLOB NOT NULL, canonical_payload CLOB NOT NULL
);
CREATE TABLE IF NOT EXISTS operations (
 op_id VARCHAR(36) PRIMARY KEY, request_payload CLOB NOT NULL,
 status INT NOT NULL, response_payload CLOB NOT NULL
);
